-- Limpeza preventiva de tabelas
DROP TABLE TB_CT_VOTO CASCADE CONSTRAINTS;
DROP TABLE TB_CT_CONSULTA CASCADE CONSTRAINTS;
DROP TABLE TB_CT_TEMA CASCADE CONSTRAINTS;
DROP TABLE TB_CT_USUARIO CASCADE CONSTRAINTS;

-- 1. Tabela de Usuários (moradores cidadãos e gestores comunitários)
CREATE TABLE TB_CT_USUARIO (
    id_usuario      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR2(100) NOT NULL,
    email           VARCHAR2(100) NOT NULL,
    senha_hash      VARCHAR2(255) NOT NULL,
    papel           VARCHAR2(20)  DEFAULT 'CIDADAO' NOT NULL,
    bairro          VARCHAR2(80)  NOT NULL,
    data_cadastro   DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CT_USUARIO PRIMARY KEY (id_usuario),
    CONSTRAINT UK_CT_USUARIO_EMAIL UNIQUE (email),
    CONSTRAINT CK_CT_USUARIO_PAPEL CHECK (papel IN ('CIDADAO', 'GESTOR'))
);

-- 2. Tabela de Temas (categorias das propostas de melhoria)
CREATE TABLE TB_CT_TEMA (
    id_tema         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome_tema       VARCHAR2(80)  NOT NULL,
    descricao       VARCHAR2(255) NOT NULL,
    status_ativo    CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_CT_TEMA PRIMARY KEY (id_tema),
    CONSTRAINT UK_CT_TEMA_NOME UNIQUE (nome_tema),
    CONSTRAINT CK_CT_TEMA_ATIVO CHECK (status_ativo IN ('S', 'N'))
);

-- 3. Tabela de Consultas Públicas (ciclo de vida: RASCUNHO -> ABERTA -> ENCERRADA)
CREATE TABLE TB_CT_CONSULTA (
    id_consulta         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_tema             NUMBER        NOT NULL,
    id_gestor           NUMBER        NOT NULL,
    titulo              VARCHAR2(150) NOT NULL,
    descricao           VARCHAR2(500) NOT NULL,
    bairro_alvo         VARCHAR2(80)  NOT NULL,
    status              VARCHAR2(20)  DEFAULT 'RASCUNHO' NOT NULL,
    data_abertura       DATE,
    data_fechamento     DATE,
    total_votos         NUMBER        DEFAULT 0 NOT NULL,
    resultado_apuracao  VARCHAR2(50)  DEFAULT 'PENDENTE' NOT NULL,
    CONSTRAINT PK_CT_CONSULTA PRIMARY KEY (id_consulta),
    CONSTRAINT FK_CT_CONSULTA_TEMA FOREIGN KEY (id_tema) REFERENCES TB_CT_TEMA (id_tema),
    CONSTRAINT FK_CT_CONSULTA_GESTOR FOREIGN KEY (id_gestor) REFERENCES TB_CT_USUARIO (id_usuario),
    CONSTRAINT CK_CT_CONSULTA_STATUS CHECK (status IN ('RASCUNHO', 'ABERTA', 'ENCERRADA'))
);

-- 4. Tabela de Votos (com regra de unicidade: 1 voto por morador por consulta)
CREATE TABLE TB_CT_VOTO (
    id_voto         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_consulta     NUMBER        NOT NULL,
    id_usuario      NUMBER        NOT NULL,
    opcao_voto      VARCHAR2(15)  NOT NULL,
    codigo_recibo   VARCHAR2(64)  NOT NULL,
    data_voto       DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CT_VOTO PRIMARY KEY (id_voto),
    CONSTRAINT FK_CT_VOTO_CONSULTA FOREIGN KEY (id_consulta) REFERENCES TB_CT_CONSULTA (id_consulta),
    CONSTRAINT FK_CT_VOTO_USUARIO FOREIGN KEY (id_usuario) REFERENCES TB_CT_USUARIO (id_usuario),
    CONSTRAINT CK_CT_VOTO_OPCAO CHECK (opcao_voto IN ('FAVOR', 'CONTRA', 'ABSTENCAO')),
    CONSTRAINT UK_CT_VOTO_UNICO UNIQUE (id_consulta, id_usuario)
);
