-- 1. Procedure de Operação (PRC_REGISTRAR_VOTO)
CREATE OR REPLACE PROCEDURE PRC_REGISTRAR_VOTO (
    p_id_consulta   IN  NUMBER,
    p_id_usuario    IN  NUMBER,
    p_opcao_voto    IN  VARCHAR2,
    p_codigo_recibo OUT VARCHAR2
) IS
    v_status_consulta   TB_CT_CONSULTA.status%TYPE;
    v_qtd_votos_exist   NUMBER := 0;
    v_opcao_formatada   VARCHAR2(15);
    v_novo_recibo       VARCHAR2(64);
BEGIN
    v_opcao_formatada := UPPER(TRIM(p_opcao_voto));

    IF v_opcao_formatada NOT IN ('FAVOR', 'CONTRA', 'ABSTENCAO') THEN
        RAISE_APPLICATION_ERROR(-20001, 'Opção inválida. Escolha FAVOR, CONTRA ou ABSTENCAO.');
    END IF;

    BEGIN
        SELECT status INTO v_status_consulta FROM TB_CT_CONSULTA WHERE id_consulta = p_id_consulta;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20002, 'Consulta #' || p_id_consulta || ' não encontrada.');
    END;

    IF v_status_consulta != 'ABERTA' THEN
        RAISE_APPLICATION_ERROR(-20003, 'Votação rejeitada: a consulta está ' || v_status_consulta || '. Deve estar ABERTA.');
    END IF;

    DECLARE
        v_dummy NUMBER;
    BEGIN
        SELECT 1 INTO v_dummy FROM TB_CT_USUARIO WHERE id_usuario = p_id_usuario;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20004, 'Usuário #' || p_id_usuario || ' não encontrado.');
    END;

    SELECT COUNT(*) INTO v_qtd_votos_exist FROM TB_CT_VOTO
     WHERE id_consulta = p_id_consulta AND id_usuario = p_id_usuario;

    IF v_qtd_votos_exist > 0 THEN
        RAISE_APPLICATION_ERROR(-20005, 'Voto duplicado detectado: o usuário já votou nesta consulta.');
    END IF;

    v_novo_recibo := 'REC-C' || p_id_consulta || '-U' || p_id_usuario || '-' || TO_CHAR(SYSDATE, 'YYYYMMDDHH24MISS');

    INSERT INTO TB_CT_VOTO (id_consulta, id_usuario, opcao_voto, codigo_recibo, data_voto)
    VALUES (p_id_consulta, p_id_usuario, v_opcao_formatada, v_novo_recibo, SYSDATE);

    UPDATE TB_CT_CONSULTA SET total_votos = total_votos + 1 WHERE id_consulta = p_id_consulta;

    p_codigo_recibo := v_novo_recibo;
    DBMS_OUTPUT.PUT_LINE('>> SUCESSO: Voto registrado! Recibo: ' || p_codigo_recibo);
END PRC_REGISTRAR_VOTO;
