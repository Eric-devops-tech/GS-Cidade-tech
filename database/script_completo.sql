DECLARE
    v_id_consulta           TB_CT_CONSULTA.id_consulta%TYPE := 1;
    v_titulo                TB_CT_CONSULTA.titulo%TYPE;
    v_bairro                TB_CT_CONSULTA.bairro_alvo%TYPE;
